
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

/*
 * Host-only BFS Oracle.
 * oracle.c already includes solver_original.c.
 *
 * This program generates all Depth-11 states and
 * their optimal 11-move solutions as an Assembly
 * lookup table.
 */
#include "oracle.c"

int main(void)
{
    /* Step 1: Generate exact BFS distances. */
    uint8_t *dist = oracle_distances();

    if (!dist) {
        fprintf(stderr, "Cannot construct BFS distances\n");
        return 1;
    }

    /* Step 2: Generate moves toward solved state. */
    uint8_t diameter = 0;
    uint8_t *toward = build_table(&diameter);

    if (!toward || diameter != 11) {
        fprintf(stderr, "Cannot construct BFS moves or diameter != 11\n");
        free(toward);
        free(dist);
        return 1;
    }

    unsigned count = 0;
    uint32_t previous_key = 0;

    /* Step 3: Generate Assembly table header. */
    puts("# Generated by generate_depth11.c using the HW1 BFS oracle.");
    puts(".section .rodata,\"a\",@progbits");
    puts(".balign 4");
    puts(".globl rubik_depth11_table");
    puts("rubik_depth11_table:");

    /* Step 4: Scan all 3,674,160 legal cube states. */
    for (uint32_t rank = 0; rank < STATES; ++rank) {
        /* Only retain states whose optimal depth is 11. */
        if (dist[rank] != 11)
            continue;

        /* Extract permutation and orientation ranks. */
        uint32_t p = rank / ORIENTATIONS;
        uint32_t o = rank % ORIENTATIONS;

        /*
         * Unique key:
         * 10 bits are sufficient for orientation (0..728).
         */
        uint32_t key = (p << 10) | o;

        /* Verify strict ordering for binary search. */
        if (count && key <= previous_key) {
            fprintf(stderr, "Keys are not strictly increasing\n");
            free(toward);
            free(dist);
            return 2;
        }

        previous_key = key;

        /* Step 5: Construct the optimal solution path. */
        uint32_t current = rank;
        uint8_t path[11];

        for (unsigned step = 0; step < 11; ++step) {
            uint8_t move = toward[current];

            if (move >= MOVES) {
                fprintf(stderr, "Invalid move at rank %u\n", rank);
                free(toward);
                free(dist);
                return 3;
            }

            path[step] = move;

            /* Apply move using the original cube model. */
            state_t state;
            unrank_state(current, &state);

            state = apply_move(state, move);
            current = rank_state(&state);

            /* Remaining distance must decrease by one. */
            if (dist[current] != (uint8_t) (10 - step)) {
                fprintf(stderr, "Non-decreasing distance at rank %u\n", rank);
                free(toward);
                free(dist);
                return 4;
            }
        }

        /* Step 6: Verify the complete solution. */
        if (current != 0 || !oracle_replay(rank, path, 11)) {
            fprintf(stderr, "Replay failure at rank %u\n", rank);

            free(toward);
            free(dist);
            return 5;
        }

        /*
         * Step 7: Write one Assembly table entry.
         *
         * 4 bytes: state key
         * 11 bytes: solution moves
         * 1 byte: padding
         *
         * Total = 16 bytes per entry.
         */
        printf("    .word 0x%08x\n", key);
        printf("    .byte ");

        for (unsigned step = 0; step < 11; ++step) {
            printf("%s%u", step ? ", " : "", (unsigned) path[step]);
        }

        puts("\n    .byte 0");

        ++count;
    }

    /* Step 8: Print results to stderr. */
    fprintf(stderr, "Depth 11: %u states, %u bytes\n", count, count * 16u);

    free(toward);
    free(dist);

    /* Confirm all 2,644 Depth-11 states are present. */
    return count == 2644 ? 0 : 6;
}
